"""Generate common/generated/element_database.h from common/assets/element_data.csv.

Usage: generate_element_data.py <element_data.csv> <element_database.h>
"""

import csv
import sys


def main(src: str, dst: str) -> None:
    with open(src, encoding="utf-8") as f:
        rows = list(csv.DictReader(line for line in f if not line.startswith("#")))
    if [int(r["z"]) for r in rows] != list(range(1, len(rows) + 1)):
        raise SystemExit("element_data.csv must list Z = 1, 2, ... in order")
    out = [
        "// Auto-generated by common/scripts/generate_element_data.py - DO NOT EDIT",
        "// Source: common/assets/element_data.csv",
        "#pragma once",
        "#define AMCSET_ELEMENT_DATABASE \\",
    ]
    entries = []
    for r in rows:
        entries.append(
            "  ElementRecord{%s, \"%s\", \"%s\", %s, %s, %s, %s, %s, %s, %s, %s, %s, %s}"
            % (r["z"], r["symbol"], r["name"], r["mai_mass_number"], r["mai_mass_amu"],
               r["natural_weight_amu"], r["density_g_cm3"], r["atomic_density_cm3"],
               r["fermi_velocity_v0"], r["sublimation_energy_eV"], r["gas_density_g_cm3"],
               r["gas_atomic_density_cm3"], r["mean_excitation_energy_eV"]))
    out.append(", \\\n".join(entries))
    out.append("")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
