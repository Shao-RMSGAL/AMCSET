Mat3 uniform_rotation(double u1, double u2, double u3) noexcept {
  // Shoemake, "Uniform random rotations", Graphics Gems III (1992): a
  // uniform unit quaternion.
  const double a = std::sqrt(1.0 - u1);
  const double b = std::sqrt(u1);
  const double x = a * std::sin(2.0 * pi_v * u2);
  const double y = a * std::cos(2.0 * pi_v * u2);
  const double z = b * std::sin(2.0 * pi_v * u3);
  const double w = b * std::cos(2.0 * pi_v * u3);
  return Mat3::from_rows({1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - z * w), 2.0 * (x * z + y * w)},
                         {2.0 * (x * y + z * w), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - x * w)},
                         {2.0 * (x * z - y * w), 2.0 * (y * z + x * w), 1.0 - 2.0 * (x * x + y * y)});
}

Mat3 sample_to_laboratory() noexcept { return Mat3::from_rows({0, 0, -1}, {1, 0, 0}, {0, -1, 0}); }

std::vector<Mat3> lattice_rotations(const Lattice &lattice) {
  const auto &m = lattice.vectors_A();
  const double a = norm(m[0]);
  const double b = norm(m[1]);
  const double c = norm(m[2]);
  const auto right = [](const Vec3 &u, const Vec3 &v) { return std::abs(dot(u, v)) <= 1e-6 * norm(u) * norm(v); };
  const auto same = [](double u, double v) { return std::abs(u - v) <= 1e-6 * std::max(u, v); };
  const double quarter = 0.5 * pi_v;
  if (lattice.is_hexagonal()) {
    return closure({rotation_about(m[2], pi_v / 3.0), rotation_about(m[0], pi_v)});
  }
  if (!(right(m[0], m[1]) && right(m[0], m[2]) && right(m[1], m[2]))) return {Mat3::identity()};
  if (same(a, b) && same(b, c)) {
    return closure({rotation_about(m[0], quarter), rotation_about(m[1], quarter), rotation_about(m[2], quarter)});
  }
  if (same(a, b)) return closure({rotation_about(m[2], quarter), rotation_about(m[0], pi_v)});
  if (same(b, c)) return closure({rotation_about(m[0], quarter), rotation_about(m[1], pi_v)});
  if (same(a, c)) return closure({rotation_about(m[1], quarter), rotation_about(m[0], pi_v)});
  return closure({rotation_about(m[0], pi_v), rotation_about(m[1], pi_v)});
}

double misorientation_rad(const Mat3 &a, const Mat3 &b, const std::vector<Mat3> &symmetry) {
  // The rotation from crystal b to crystal a, up to the crystal's own
  // rotations: the largest trace is the smallest angle.
  const Mat3 d = a.transposed() * b;
  double trace = -1.0;
  const auto trace_with = [&](const Mat3 &s) {
    double t = 0.0;
    for (int i = 0; i < 3; ++i) t += dot(d[i], s.column(i));
    return t;
  };
  if (symmetry.empty()) trace = trace_with(Mat3::identity());
  for (const auto &s : symmetry) trace = std::max(trace, trace_with(s));
  return std::acos(std::clamp(0.5 * (trace - 1.0), -1.0, 1.0));
}

