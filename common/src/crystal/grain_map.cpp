std::string to_string(Polycrystal::Source s) {
  switch (s) {
  case Polycrystal::Source::voronoi: return "voronoi";
  case Polycrystal::Source::grain_file: return "file";
  case Polycrystal::Source::neper: return "neper";
  case Polycrystal::Source::ebsd: return "ebsd";
  }
  return "voronoi";
}

Polycrystal::Source parse_polycrystal_source(std::string_view s) {
  if (s == "voronoi" || s == "generated") return Polycrystal::Source::voronoi;
  if (s == "file" || s == "grains" || s == "grain_file") return Polycrystal::Source::grain_file;
  if (s == "neper" || s == "tess") return Polycrystal::Source::neper;
  if (s == "ebsd") return Polycrystal::Source::ebsd;
  throw std::invalid_argument("unknown source of grains '" + std::string(s) + "' (voronoi, file, neper, ebsd)");
}

std::string to_string(Polycrystal::Texture t) {
  switch (t) {
  case Polycrystal::Texture::random: return "random";
  case Polycrystal::Texture::fiber: return "fiber";
  case Polycrystal::Texture::mosaic: return "mosaic";
  }
  return "random";
}

Polycrystal::Texture parse_texture(std::string_view s) {
  if (s == "random") return Polycrystal::Texture::random;
  if (s == "fiber" || s == "fibre") return Polycrystal::Texture::fiber;
  if (s == "mosaic") return Polycrystal::Texture::mosaic;
  throw std::invalid_argument("unknown texture '" + std::string(s) + "' (random, fiber, mosaic)");
}

void check_polycrystal(const Polycrystal &p, const std::string &where) {
  const double size = in_units(p.grain_size, angstrom);
  const double py = in_units(p.period_y, angstrom);
  const double pz = in_units(p.period_z, angstrom);
  if (p.source == Polycrystal::Source::voronoi) {
    if (!(size >= 10.0) || !(size <= 1e9)) {
      throw std::invalid_argument(where + ".grain_size: 10 A to 10 cm, got " + num(size) + " A");
    }
  } else if (p.file.empty()) {
    throw std::invalid_argument(where + ".file: give the file of the grains");
  }
  for (const auto &[period, key] : {std::pair{py, ".period"}, std::pair{pz, ".period"}}) {
    if (!(period >= 0.0) || !(period <= 1e10) || (period > 0.0 && period < 10.0)) {
      throw std::invalid_argument(where + key + ": 0 (automatic) or 10 A to 1 m, got " + num(period) + " A");
    }
  }
  const double spread = in_units(p.spread, degree);
  if (!(spread >= 0.0) || !(spread <= 180.0)) {
    throw std::invalid_argument(where + ".spread: 0 to 180 degrees, got " + num(spread));
  }
  const double width = in_units(p.boundary_width, angstrom);
  if (!(width >= 0.0) || !(width <= max_boundary_width_A)) {
    throw std::invalid_argument(where + ".boundary_width: 0 to " + num(max_boundary_width_A) + " A, got " + num(width) +
                                " A");
  }
  const double registry = in_units(p.registry_below, degree);
  if (!(registry >= 0.0) || !(registry <= max_registry_deg)) {
    throw std::invalid_argument(where + ".registry_below: 0 (off) to " + num(max_registry_deg) + " degrees, got " +
                                num(registry));
  }
  const double scale = in_units(p.scale, angstrom);
  if (!(scale > 0.0) || !std::isfinite(scale)) throw std::invalid_argument(where + ".scale: must be positive");
  const double mis = in_units(p.misorientation, degree);
  if (!(mis > 0.0) || !(mis <= 180.0)) {
    throw std::invalid_argument(where + ".misorientation: above 0 and at most 180 degrees, got " + num(mis));
  }
  if (p.phase < 0) throw std::invalid_argument(where + ".phase: 0 (every phase) or a phase number");
}

