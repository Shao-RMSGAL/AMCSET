GrainMap GrainMap::from_seeds(std::vector<Grain> grains, std::vector<Seed> seeds, double period_y_A, double period_z_A,
                              bool columnar) {
  if (seeds.empty()) throw std::invalid_argument("grain map: no seeds");
  if (!(period_y_A > 0.0) || !(period_z_A > 0.0) || !std::isfinite(period_y_A) || !std::isfinite(period_z_A)) {
    throw std::invalid_argument("grain map: the lateral periods must be positive");
  }
  if (seeds.size() > 0xFFFFFFF0ull) throw std::invalid_argument("grain map: too many seeds");
  GrainMap m;
  m.columnar_ = columnar;
  m.period_[0] = period_y_A;
  m.period_[1] = period_z_A;
  double w_lo = infinity;
  double w_hi = -infinity;
  double x_lo = infinity;
  double x_hi = -infinity;
  std::size_t none = 0;
  for (auto &s : seeds) {
    if (s.grain < -1 || s.grain >= static_cast<int>(grains.size())) {
      throw std::invalid_argument("grain map: a seed belongs to grain " + std::to_string(s.grain) + ", which does not exist");
    }
    if (!std::isfinite(s.position_A.x) || !std::isfinite(s.position_A.y) || !std::isfinite(s.position_A.z) ||
        !std::isfinite(s.weight_A2)) {
      throw std::invalid_argument("grain map: a seed's position or weight is not a number");
    }
    s.position_A.y = wrap(s.position_A.y, period_y_A);
    s.position_A.z = wrap(s.position_A.z, period_z_A);
    if (columnar) s.position_A.x = 0.0;
    w_lo = std::min(w_lo, s.weight_A2);
    w_hi = std::max(w_hi, s.weight_A2);
    x_lo = std::min(x_lo, s.position_A.x);
    x_hi = std::max(x_hi, s.position_A.x);
    none += s.grain < 0 ? 1 : 0;
  }
  // (A power diagram does not change when every weight is shifted.)
  for (auto &s : seeds) s.weight_A2 -= w_lo;
  m.weight_max_ = w_hi - w_lo;
  m.ungrained_ = static_cast<double>(none) / static_cast<double>(seeds.size());

  // Buckets of about two seeds.
  const double n = static_cast<double>(seeds.size());
  const double lx = columnar ? 1.0 : std::max(x_hi - x_lo, 1e-6);
  const double h = columnar ? std::sqrt(2.0 * period_y_A * period_z_A / n)
                            : std::cbrt(2.0 * lx * period_y_A * period_z_A / n);
  m.buckets_[0] = columnar ? 1 : std::clamp(static_cast<int>(lx / h), 1, 512);
  m.buckets_[1] = std::clamp(static_cast<int>(period_y_A / h), 1, 2048);
  m.buckets_[2] = std::clamp(static_cast<int>(period_z_A / h), 1, 2048);
  m.bucket_A_[0] = lx / m.buckets_[0];
  m.bucket_A_[1] = period_y_A / m.buckets_[1];
  m.bucket_A_[2] = period_z_A / m.buckets_[2];
  m.x_lo_ = columnar ? 0.0 : x_lo;
  const auto bucket_of = [&m](const Vec3 &p) {
    const int ix = m.columnar_ ? 0 : std::clamp(static_cast<int>((p.x - m.x_lo_) / m.bucket_A_[0]), 0, m.buckets_[0] - 1);
    const int iy = std::min(static_cast<int>(p.y / m.bucket_A_[1]), m.buckets_[1] - 1);
    const int iz = std::min(static_cast<int>(p.z / m.bucket_A_[2]), m.buckets_[2] - 1);
    return (static_cast<std::size_t>(ix) * static_cast<std::size_t>(m.buckets_[1]) + static_cast<std::size_t>(iy)) *
               static_cast<std::size_t>(m.buckets_[2]) +
           static_cast<std::size_t>(iz);
  };
  const std::size_t count = static_cast<std::size_t>(m.buckets_[0]) * m.buckets_[1] * m.buckets_[2];
  m.bucket_start_.assign(count + 1, 0);
  for (const auto &s : seeds) ++m.bucket_start_[bucket_of(s.position_A) + 1];
  for (std::size_t i = 0; i < count; ++i) m.bucket_start_[i + 1] += m.bucket_start_[i];
  m.bucket_seed_.resize(seeds.size());
  std::vector<std::uint32_t> next(m.bucket_start_.begin(), m.bucket_start_.end() - 1);
  for (std::size_t i = 0; i < seeds.size(); ++i) {
    m.bucket_seed_[next[bucket_of(seeds[i].position_A)]++] = static_cast<std::uint32_t>(i);
  }
  m.grains_ = std::move(grains);
  m.seeds_ = std::move(seeds);
  return m;
}

GrainMap GrainMap::from_voxels(std::vector<Grain> grains, std::vector<int> ids, std::array<int, 3> n, double depth_A,
                               double period_y_A, double period_z_A) {
  if (n[0] < 1 || n[1] < 1 || n[2] < 1 ||
      ids.size() != static_cast<std::size_t>(n[0]) * static_cast<std::size_t>(n[1]) * static_cast<std::size_t>(n[2])) {
    throw std::invalid_argument("grain map: " + std::to_string(ids.size()) + " voxels do not fill a grid of " +
                                std::to_string(n[0]) + " x " + std::to_string(n[1]) + " x " + std::to_string(n[2]));
  }
  if (!(depth_A > 0.0) || !(period_y_A > 0.0) || !(period_z_A > 0.0) || !std::isfinite(depth_A) ||
      !std::isfinite(period_y_A) || !std::isfinite(period_z_A)) {
    throw std::invalid_argument("grain map: the depth and the lateral periods must be positive");
  }
  std::size_t none = 0;
  for (int id : ids) {
    if (id < -1 || id >= static_cast<int>(grains.size())) {
      throw std::invalid_argument("grain map: a voxel belongs to grain " + std::to_string(id) + ", which does not exist");
    }
    none += id < 0 ? 1 : 0;
  }
  GrainMap m;
  m.grains_ = std::move(grains);
  m.ungrained_ = static_cast<double>(none) / static_cast<double>(ids.size());
  m.ids_ = std::move(ids);
  m.n_ = n;
  m.depth_A_ = depth_A;
  m.period_[0] = period_y_A;
  m.period_[1] = period_z_A;
  return m;
}

GrainMap GrainMap::with_grains(std::vector<Grain> grains) const {
  if (grains.size() != grains_.size()) {
    throw std::invalid_argument("grain map: " + std::to_string(grains.size()) + " grains instead of " +
                                std::to_string(grains_.size()));
  }
  GrainMap m = *this;
  m.grains_ = std::move(grains);
  return m;
}

int GrainMap::voxel(int i, int j, int k) const noexcept {
  if (ids_.empty() || i < 0 || i >= n_[0]) return -1;
  j = (j % n_[1] + n_[1]) % n_[1];
  k = (k % n_[2] + n_[2]) % n_[2];
  return ids_[(static_cast<std::size_t>(i) * static_cast<std::size_t>(n_[1]) + static_cast<std::size_t>(j)) *
                  static_cast<std::size_t>(n_[2]) +
              static_cast<std::size_t>(k)];
}

GrainMap::At GrainMap::at(const Vec3 &r, double cap_A) const {
  if (is_voxels()) return at_voxels(r);
  if (seeds_.empty()) return {};
  return at_seeds(r, cap_A, false);
}

GrainMap::At GrainMap::at_brute_force(const Vec3 &r) const {
  if (is_voxels()) return at_voxels(r);
  if (seeds_.empty()) return {};
  return at_seeds(r, infinity, true);
}

GrainMap::At GrainMap::at_seeds(const Vec3 &r, double cap_A, bool brute_force) const {
  const double x = columnar_ ? 0.0 : r.x;
  const double y = wrap(r.y, period_[0]);
  const double z = wrap(r.z, period_[1]);
  const double half = 0.5 * std::min(period_[0], period_[1]);

  // Every seed (with its displacement from r) whose distance may be below
  // \p radius: the buckets the sphere touches, or all seeds and their
  // lateral images when the sphere is as wide as the map.
  const auto visit = [&](double radius, auto &&f) {
    if (brute_force || !(radius < half)) {
      for (std::size_t i = 0; i < seeds_.size(); ++i) {
        const auto &s = seeds_[i];
        for (int a = -1; a <= 1; ++a) {
          for (int b = -1; b <= 1; ++b) {
            f(i, Vec3{s.position_A.x - x, s.position_A.y - y + a * period_[0], s.position_A.z - z + b * period_[1]});
          }
        }
      }
      return;
    }
    const int x0 = columnar_ ? 0 : std::clamp(static_cast<int>(std::floor((x - radius - x_lo_) / bucket_A_[0])), 0, buckets_[0] - 1);
    const int x1 = columnar_ ? 0 : std::clamp(static_cast<int>(std::floor((x + radius - x_lo_) / bucket_A_[0])), 0, buckets_[0] - 1);
    const int y0 = static_cast<int>(std::floor((y - radius) / bucket_A_[1]));
    const int y1 = static_cast<int>(std::floor((y + radius) / bucket_A_[1]));
    const int z0 = static_cast<int>(std::floor((z - radius) / bucket_A_[2]));
    const int z1 = static_cast<int>(std::floor((z + radius) / bucket_A_[2]));
    const int ny = std::min(y1 - y0 + 1, buckets_[1]);
    const int nz = std::min(z1 - z0 + 1, buckets_[2]);
    for (int ix = x0; ix <= x1; ++ix) {
      for (int jy = 0; jy < ny; ++jy) {
        const int iy = ((y0 + jy) % buckets_[1] + buckets_[1]) % buckets_[1];
        for (int jz = 0; jz < nz; ++jz) {
          const int iz = ((z0 + jz) % buckets_[2] + buckets_[2]) % buckets_[2];
          const std::size_t bucket = (static_cast<std::size_t>(ix) * static_cast<std::size_t>(buckets_[1]) +
                                      static_cast<std::size_t>(iy)) *
                                         static_cast<std::size_t>(buckets_[2]) +
                                     static_cast<std::size_t>(iz);
          for (std::uint32_t k = bucket_start_[bucket]; k < bucket_start_[bucket + 1]; ++k) {
            const std::size_t i = bucket_seed_[k];
            const auto &s = seeds_[i];
            f(i, Vec3{s.position_A.x - x, nearest_image(s.position_A.y - y, period_[0]),
                      nearest_image(s.position_A.z - z, period_[1])});
          }
        }
      }
    }
  };

  // The seed with the smallest power distance |r - p|^2 - w. A seed farther
  // than sqrt(best + w_max) cannot win, so the search ends when the sphere
  // looked at is that large.
  std::size_t best = seeds_.size();
  double best_power = infinity;
  Vec3 best_d;
  double radius = std::max({columnar_ ? 0.0 : bucket_A_[0], bucket_A_[1], bucket_A_[2]});
  for (;;) {
    visit(radius, [&](std::size_t i, const Vec3 &d) {
      const double power = dot(d, d) - seeds_[i].weight_A2;
      if (power < best_power || (power == best_power && i < best)) {
        best_power = power;
        best = i;
        best_d = d;
      }
    });
    if (brute_force || !(radius < half)) break;
    if (best < seeds_.size() && std::sqrt(std::max(best_power + weight_max_, 0.0)) <= radius) break;
    radius *= 2.0;
  }
  At result;
  result.grain = seeds_[best].grain;
  if (!(cap_A > 0.0)) return result;

  // The nearest boundary: the plane of equal power distance with a seed j
  // of another grain is (D_j - D_i) / (2 |p_j - p_i|) away. Seeds beyond
  // sqrt(D_i + w_max) + 2 cap are farther away than the cap.
  const double reach = std::sqrt(std::max(best_power + weight_max_, 0.0)) + 2.0 * std::min(cap_A, 1e30);
  visit(brute_force ? infinity : reach, [&](std::size_t j, const Vec3 &d) {
    if (seeds_[j].grain == result.grain) return;
    const double power = dot(d, d) - seeds_[j].weight_A2;
    const double apart = norm(d - best_d);
    if (!(apart > 0.0)) return;
    result.boundary_A = std::min(result.boundary_A, std::max(power - best_power, 0.0) / (2.0 * apart));
  });
  return result;
}

GrainMap::At GrainMap::at_voxels(const Vec3 &r) const {
  const double dx = depth_A_ / n_[0];
  const double dy = period_[0] / n_[1];
  const double dz = period_[1] / n_[2];
  const double y = wrap(r.y, period_[0]);
  const double z = wrap(r.z, period_[1]);
  const int ix = std::clamp(static_cast<int>(std::floor(r.x / dx)), 0, n_[0] - 1);
  const int iy = std::min(static_cast<int>(y / dy), n_[1] - 1);
  const int iz = std::min(static_cast<int>(z / dz), n_[2] - 1);
  const auto id = [this](int i, int j, int k) {
    j = (j % n_[1] + n_[1]) % n_[1];
    k = (k % n_[2] + n_[2]) % n_[2];
    return ids_[(static_cast<std::size_t>(i) * static_cast<std::size_t>(n_[1]) + static_cast<std::size_t>(j)) *
                    static_cast<std::size_t>(n_[2]) +
                static_cast<std::size_t>(k)];
  };
  At result;
  result.grain = id(ix, iy, iz);
  // The faces of this voxel behind which another grain lies.
  const auto face = [&](bool other, double distance) {
    if (other) result.boundary_A = std::min(result.boundary_A, std::max(distance, 0.0));
  };
  if (ix > 0) face(id(ix - 1, iy, iz) != result.grain, r.x - ix * dx);
  if (ix + 1 < n_[0]) face(id(ix + 1, iy, iz) != result.grain, (ix + 1) * dx - r.x);
  face(id(ix, iy - 1, iz) != result.grain, y - iy * dy);
  face(id(ix, iy + 1, iz) != result.grain, (iy + 1) * dy - y);
  face(id(ix, iy, iz - 1) != result.grain, z - iz * dz);
  face(id(ix, iy, iz + 1) != result.grain, (iz + 1) * dz - z);
  return result;
}

// ---------------------------------------------------------------------------
// Generated grains
// ---------------------------------------------------------------------------

GrainMap generate_voronoi(const Polycrystal &p, const Mat3 &base, double depth_A) {
  const double size = in_units(p.grain_size, angstrom);
  if (!(size > 0.0) || !(depth_A > 0.0)) throw std::invalid_argument("polycrystal: grain size and depth must be positive");
  double py = in_units(p.period_y, angstrom);
  double pz = in_units(p.period_z, angstrom);
  if (!(py > 0.0)) py = 8.0 * size;
  if (!(pz > 0.0)) pz = 8.0 * size;
  // Seeds also one grain size above and below the layer: the grains at its
  // faces are then cut like those inside.
  const double margin = p.columnar ? 0.0 : size;
  const double extent = depth_A + 2.0 * margin;
  const double per_grain = p.columnar ? 0.25 * pi_v * size * size : pi_v / 6.0 * size * size * size;
  const double expected = (p.columnar ? py * pz : extent * py * pz) / per_grain;
  if (!(expected <= static_cast<double>(max_grains))) {
    throw std::invalid_argument("polycrystal: about " + num(expected) + " grains (grains of " + num(size) +
                                " A in " + num(py) + " x " + num(pz) + " A): more than the limit of " +
                                std::to_string(max_grains) + "; use larger grains or a smaller period");
  }
  const std::size_t n = std::max<std::size_t>(1, static_cast<std::size_t>(std::llround(expected)));
  const double spread = in_units(p.spread, radian);
  Random random(p.seed);
  std::vector<Grain> grains(n);
  std::vector<GrainMap::Seed> seeds(n);
  for (std::size_t i = 0; i < n; ++i) {
    auto &s = seeds[i];
    s.position_A = {p.columnar ? 0.0 : -margin + extent * random.uniform(), py * random.uniform(), pz * random.uniform()};
    s.grain = static_cast<int>(i);
    auto &g = grains[i];
    // (The same number of draws for every texture.)
    const double u1 = random.uniform();
    const double u2 = random.uniform();
    const double u3 = random.uniform();
    const double angle = spread * random.gaussian();
    switch (p.texture) {
    case Polycrystal::Texture::random:
      g.rotation = uniform_rotation(u1, u2, u3);
      break;
    case Polycrystal::Texture::fiber: {
      // The crystal's surface plane, turned about the normal (the depth
      // axis), then tilted by the spread about an axis in the surface.
      const Vec3 axis{0.0, std::cos(2.0 * pi_v * u2), std::sin(2.0 * pi_v * u2)};
      g.rotation = rotation_about(axis, angle) * rotation_about({1, 0, 0}, 2.0 * pi_v * u1) * base;
      break;
    }
    case Polycrystal::Texture::mosaic: {
      // The crystal's orientation, turned by the spread about a random axis.
      const double c = 2.0 * u1 - 1.0;
      const double s2 = std::sqrt(std::max(0.0, 1.0 - c * c));
      const Vec3 axis{c, s2 * std::cos(2.0 * pi_v * u2), s2 * std::sin(2.0 * pi_v * u2)};
      g.rotation = rotation_about(axis, angle) * base;
      break;
    }
    }
    (void)u3;
    g.origin_A = s.position_A;
  }
  return GrainMap::from_seeds(std::move(grains), std::move(seeds), py, pz, p.columnar);
}

