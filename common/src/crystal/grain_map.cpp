constexpr double infinity = std::numeric_limits<double>::infinity();

std::string num(double v) {
  char buf[48];
  std::snprintf(buf, sizeof buf, "%.6g", v);
  return buf;
}

/*!
 * SplitMix64: the generator of the grains. One description gives one set of
 * grains, whatever the run's seed and the number of threads.
 */
struct Random {
  std::uint64_t state;
  explicit Random(std::uint64_t seed) : state(seed * 0x9E3779B97F4A7C15ull + 0x632BE59BD9B4E019ull) {}
  std::uint64_t next() noexcept {
    std::uint64_t z = (state += 0x9E3779B97F4A7C15ull);
    z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ull;
    z = (z ^ (z >> 27)) * 0x94D049BB133111EBull;
    return z ^ (z >> 31);
  }
  //! In [0, 1).
  double uniform() noexcept { return static_cast<double>(next() >> 11) * (1.0 / 9007199254740992.0); }
  double gaussian() noexcept {
    const double u1 = 1.0 - uniform(); // (0, 1]
    const double u2 = uniform();
    return std::sqrt(-2.0 * std::log(u1)) * std::cos(2.0 * pi_v * u2);
  }
};

//! \p v in [0, period).
double wrap(double v, double period) noexcept {
  v = std::fmod(v, period);
  if (v < 0.0) v += period;
  return v < period ? v : 0.0;
}

double nearest_image(double d, double period) noexcept { return d - period * std::nearbyint(d / period); }

bool same_rotation(const Mat3 &a, const Mat3 &b) noexcept {
  for (int i = 0; i < 3; ++i) {
    for (int j = 0; j < 3; ++j) {
      if (std::abs(a[i][j] - b[i][j]) > 1e-9) return false;
    }
  }
  return true;
}

//! The group generated by \p generators.
std::vector<Mat3> closure(const std::vector<Mat3> &generators) {
  std::vector<Mat3> group{Mat3::identity()};
  for (std::size_t done = 0; done < group.size() && group.size() < 64; ++done) {
    for (const auto &g : generators) {
      const Mat3 m = g * group[done];
      if (std::none_of(group.begin(), group.end(), [&](const Mat3 &o) { return same_rotation(o, m); })) group.push_back(m);
    }
  }
  return group;
}

