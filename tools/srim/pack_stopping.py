"""Pack SR Module outputs (results/stopping/sr_ZZZ_ZZZ_[sg].txt) into one AMCSET stopping-table file.

Output format (UTF-8 text, optionally gzip'ed):
  # comment lines
  amcset-stopping-table 1
  source <free text>
  energy_unit keV
  stopping_unit eV/(1e15 atoms/cm2)
  energies <n> <E_1> ... <E_n>
  table <z1> <m1_amu> <z2> <phase s|g> <n>
  Se <n values>
  Sn <n values>
  ...
"""
import csv, gzip, os, sys
src = sys.argv[1] if len(sys.argv) > 1 else 'results/stopping'
dst = sys.argv[2] if len(sys.argv) > 2 else 'results/srim2013_stopping.amcset.gz'
jobs = list(csv.DictReader(open('sr_jobs.csv')))
energies = None
out = []
bad = []
for j in jobs:
    fn = os.path.join(src, j['id'] + '.txt')
    if not os.path.exists(fn):
        bad.append(j['id']); continue
    e, se, sn = [], [], []
    for line in open(fn, encoding='latin-1'):
        p = line.split()
        if len(p) == 3:
            try:
                v = [float(x) for x in p]
            except ValueError:
                continue
            e.append(v[0]); se.append(v[1]); sn.append(v[2])
    if energies is None:
        energies = e
    if len(e) != len(energies) or any(abs(a - b) > 1e-6 * b for a, b in zip(e, energies)):
        bad.append(j['id']); continue
    ph = 'g' if j['phase'] == '1' else 's'
    out.append('table %s %s %s %s %d\nSe %s\nSn %s\n' % (j['z1'], j['m1'], j['z2'], ph, len(e),
               ' '.join('%.4g' % x for x in se), ' '.join('%.4g' % x for x in sn)))
with gzip.open(dst, 'wt', encoding='utf-8') as f:
    f.write('# Electronic and nuclear stopping cross sections extracted from the SRIM-2013 SR Module\n')
    f.write('# (SRIM is (c) J. F. Ziegler; free for non-commercial use). Generated by pack_stopping.py.\n')
    f.write('amcset-stopping-table 1\nsource SRIM-2013.00 SR Module\nenergy_unit keV\nstopping_unit eV/(1e15 atoms/cm2)\n')
    f.write('energies %d %s\n' % (len(energies), ' '.join('%.4g' % x for x in energies)))
    f.writelines(out)
print('tables', len(out), 'bad', len(bad), bad[:10])
